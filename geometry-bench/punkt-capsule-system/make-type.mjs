/* Writes type-outlines.mjs: Barlow Condensed Medium outlines for the poster's
 * dates and captions, so the engine and the offline editor need no font loading.
 * Barlow is SIL OFL 1.1; the licence ships beside the font in PosterCore.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import * as fontkit from 'fontkit';

const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../..');
const file=path.join(root,'Sources/PosterCore/Resources/Fonts/barlowcondensed/BarlowCondensed-Medium.ttf');
const font=fontkit.openSync(file),chars=' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,-–/:+&';
// fontkit, not opentype.js: opentype.js 2.0 drops contours from this file's later glyphs.
const glyphs={};
for(const c of chars){const g=font.glyphForCodePoint(c.codePointAt(0));glyphs[c]={d:g.path.toSVG(),advance:g.advanceWidth};}
const table={font:'Barlow Condensed Medium',license:'SIL Open Font License 1.1',
 sha256:crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'),
 unitsPerEm:font.unitsPerEm,capHeight:font.capHeight,glyphs};
fs.writeFileSync(path.join(here,'type-outlines.mjs'),`// Generated by make-type.mjs. Do not edit.\nexport const TYPE=${JSON.stringify(table)};\n`);
console.log(`Wrote ${chars.length} Barlow Condensed Medium outlines`);
