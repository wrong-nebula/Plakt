// Extracts glyph outlines once, so the editor and its SVGs need no font files.
// Latin faces are SIL OFL fonts from the project; Japanese outlines come from the
// macOS Hiragino Sans W6 system font for local study only (not redistributable).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as fontkit from 'fontkit';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../..'),ofl=path.join(root,'geometry-bench/experiments/native-pretext-20261108/workspace/Sources/PosterCore/Resources/Fonts');
const LATIN='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;-–!?\'&+*#@()%',
 KANA='あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをんがぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽぁぃぅぇぉっゃゅょアイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲンガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポァィゥェォッャュョヴー',
 KANJI='雨木水火光色文字生日本東京夢音愛人山川空風花月星海森林雪雷電波線形美術展新年春夏秋冬青赤白黒金銀虹響時間未来心声歌舞踊映画祭国際一二三四五六七八九十百千万円大小中上下',
 JA=KANA+KANJI+'、。・「」！？';
const SOURCES=[
 {id:'archivo',name:'Archivo Black',file:path.join(ofl,'archivoblack/ArchivoBlack-Regular.ttf'),license:'SIL Open Font License 1.1',chars:LATIN},
 {id:'anton',name:'Anton',file:path.join(ofl,'anton/Anton-Regular.ttf'),license:'SIL Open Font License 1.1',chars:LATIN},
 {id:'mono',name:'Rubik Mono One',file:path.join(ofl,'rubikmonoone/RubikMonoOne-Regular.ttf'),license:'SIL Open Font License 1.1',chars:LATIN},
 {id:'unbounded',name:'Unbounded Black',file:path.join(ofl,'unbounded/Unbounded[wght].ttf'),license:'SIL Open Font License 1.1',chars:LATIN,variation:{wght:900}},
 {id:'hiragino',name:'Hiragino Sans W6',file:'/System/Library/Fonts/ヒラギノ角ゴシック W6.ttc',postscript:'HiraKakuProN-W6',license:'Apple system font — outlines kept for local study only',chars:JA+LATIN}
];
const r1=v=>Math.round(v*10)/10;
const out={};
for(const s of SOURCES){let font=fontkit.openSync(s.file);if(font.fonts)font=font.fonts.find(f=>f.postscriptName===s.postscript)??font.fonts[0];if(s.variation)font=font.getVariation(s.variation);
 const k=1000/font.unitsPerEm,glyphs={},missing=[];
 for(const ch of [...new Set(s.chars)]){const g=font.glyphForCodePoint(ch.codePointAt(0));if(!g||(!g.id&&ch!==' ')){missing.push(ch);continue;}
  // fontkit paths are y-up in font units; store y-down at 1000 units per em, baseline 0.
  const d=g.path.commands.map(c=>{const a=c.args.map((v,i)=>r1(i%2?-v*k:v*k));return {moveTo:'M',lineTo:'L',quadraticCurveTo:'Q',bezierCurveTo:'C',closePath:'Z'}[c.command]+a.join(' ');}).join('');
  glyphs[ch]={d,adv:r1(g.advanceWidth*k)};}
 out[s.id]={name:s.name,license:s.license,source:path.basename(s.file),ascent:r1(font.ascent*k),descent:r1(font.descent*k),capHeight:r1((font.capHeight||font.ascent*.7)*k),glyphs};
 console.log(`${s.name}: ${Object.keys(glyphs).length} glyphs${missing.length?`, missing ${missing.join('')}`:''}`);}
fs.writeFileSync(path.join(here,'fonts.mjs'),`// Generated by prepare-fonts.mjs — glyph outlines at 1000 units per em, y down, baseline 0.\nexport const FONTS=${JSON.stringify(out)};\n`);
console.log(`fonts.mjs: ${(fs.statSync(path.join(here,'fonts.mjs')).size/1024).toFixed(0)} KB`);
