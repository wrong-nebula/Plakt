// Extracts glyph outlines once, so the editor and its SVGs need no font files.
// Every face is an SIL OFL font from the project's pinned Google Fonts set.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as fontkit from 'fontkit';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../..'),ofl=path.join(root,'geometry-bench/experiments/native-pretext-20261108/workspace/Sources/PosterCore/Resources/Fonts');
const LATIN='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;-–—!?\'"&+*#@()%/°×ÄÖÜäöüÉÈÊÀÂÇéèêàâçÔôÎîÏïß';
const SOURCES=[
 {id:'archivo',name:'Archivo Black',file:'archivoblack/ArchivoBlack-Regular.ttf'},
 {id:'anton',name:'Anton',file:'anton/Anton-Regular.ttf'},
 {id:'unbounded',name:'Unbounded Black',file:'unbounded/Unbounded[wght].ttf',variation:{wght:900}},
 {id:'grotesk',name:'Space Grotesk Bold',file:'spacegrotesk/SpaceGrotesk[wght].ttf',variation:{wght:700}},
 {id:'syne',name:'Syne ExtraBold',file:'syne/Syne[wght].ttf',variation:{wght:800}},
 {id:'bodoni',name:'Bodoni Moda Black',file:'bodonimoda/BodoniModa[opsz,wght].ttf',variation:{wght:900,opsz:96}},
 {id:'mono',name:'IBM Plex Mono Bold',file:'ibmplexmono/IBMPlexMono-Bold.ttf'},
 {id:'monoton',name:'Monoton',file:'monoton/Monoton-Regular.ttf'}
];
const r1=v=>Math.round(v*10)/10,out={};
for(const s of SOURCES){let font=fontkit.openSync(path.join(ofl,s.file));if(s.variation)font=font.getVariation(s.variation);
 const k=1000/font.unitsPerEm,glyphs={},missing=[];
 for(const ch of [...new Set(LATIN)]){const g=font.glyphForCodePoint(ch.codePointAt(0));if(!g||(!g.id&&ch!==' ')){missing.push(ch);continue;}
  // fontkit paths are y-up in font units; store y-down at 1000 units per em, baseline 0.
  const d=g.path.commands.map(c=>{const a=c.args.map((v,i)=>r1(i%2?-v*k:v*k));return {moveTo:'M',lineTo:'L',quadraticCurveTo:'Q',bezierCurveTo:'C',closePath:'Z'}[c.command]+a.join(' ');}).join('');
  glyphs[ch]={d,adv:r1(g.advanceWidth*k)};}
 out[s.id]={name:s.name,license:'SIL Open Font License 1.1',source:path.basename(s.file),capHeight:r1((font.capHeight||font.ascent*.7)*k),xHeight:r1((font.xHeight||font.ascent*.5)*k),glyphs};
 console.log(`${s.name}: ${Object.keys(glyphs).length} glyphs${missing.length?`, missing ${missing.join('')}`:''}`);}
fs.writeFileSync(path.join(here,'fonts.mjs'),`// Generated by prepare-fonts.mjs — glyph outlines at 1000 units per em, y down, baseline 0.\nexport const FONTS=${JSON.stringify(out)};\n`);
console.log(`fonts.mjs: ${(fs.statSync(path.join(here,'fonts.mjs')).size/1024).toFixed(0)} KB`);
